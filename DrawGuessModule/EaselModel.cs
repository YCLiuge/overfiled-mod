using System;
using UnityEngine;
using Object = UnityEngine.Object;

namespace DrawGuessModule
{
    public static partial class PaintingSystem
    {
        private static GameObject? _easelTemplate;
        private static float _nextEaselSearch;

        private static GameObject? FindGameEasel()
        {
            if (_easelTemplate != null) return _easelTemplate;
            if (Time.unscaledTime < _nextEaselSearch) return null;
            _nextEaselSearch = Time.unscaledTime + 2;
            // Prefer the same scene furniture used by the original painting implementation.
            var original = GameObject.Find("-------------------------------------------场景/---------------------普通物体/家具店画架");
            if (original != null) return _easelTemplate = original;
            GameObject? candidate = null;
            foreach (var item in Resources.FindObjectsOfTypeAll<GameObject>())
            {
                if (item == null || item.name.IndexOf("画架", StringComparison.Ordinal) < 0) continue;
                // Never use a model generated by this module as another board's template.
                bool generated = false;
                for (var ancestor = item.transform; ancestor != null; ancestor = ancestor.parent)
                    if (ancestor.name.StartsWith("DrawGuess_", StringComparison.Ordinal)) { generated = true; break; }
                if (generated || item.GetComponentsInChildren<MeshRenderer>(true).Length == 0) continue;
                if (item.name.Replace("(Clone)", "").Trim() == "家具店画架")
                    return _easelTemplate = item;
                candidate ??= item;
            }
            return _easelTemplate = candidate;
        }

        // Reuse the game's furniture easel, as in the original renderer. Clone beneath an
        // inactive parent so furniture scripts never activate or register a second real item.
        // Only the visual clone becomes active; our own drawing quad handles clicks/texture.
        private static bool CreateGameEasel(GameObject root)
        {
            var template = FindGameEasel();
            if (template == null) return false;
            var visual = new GameObject("GameEaselVisual");
            visual.SetActive(false);
            visual.transform.SetParent(root.transform, false);
            try
            {
                var clone = Object.Instantiate(template, visual.transform, false);
                clone.name = "FurnitureEaselVisual";
                clone.transform.localPosition = Vector3.zero;
                clone.transform.localRotation = Quaternion.identity;
                // Instantiate(source) in the original code preserved the source world scale.
                // Our extra channel parent is unscaled, so explicitly preserve that same scale.
                clone.transform.localScale = template.transform.lossyScale;
                foreach (var behaviour in clone.GetComponentsInChildren<Behaviour>(true))
                {
                    behaviour.enabled = false;
                    Object.DestroyImmediate(behaviour);
                }
                foreach (var collider in clone.GetComponentsInChildren<Collider>(true))
                    Object.DestroyImmediate(collider);
                foreach (var body in clone.GetComponentsInChildren<Rigidbody>(true))
                    Object.DestroyImmediate(body);
                clone.SetActive(true);
                visual.SetActive(true);
                // Keep selection available on the original frame as well as on the canvas.
                var hitbox = clone.AddComponent<BoxCollider>();
                hitbox.center = new Vector3(0, 1.1f, .12f);
                hitbox.size = new Vector3(1.4f, 2.2f, .5f);
                return true;
            }
            catch (Exception e)
            {
                visual.SetActive(false); Object.Destroy(visual);
                _easelTemplate = null; _nextEaselSearch = Time.unscaledTime + 10;
                MelonLoader.MelonLogger.Msg("[DrawGuess] 原版画架模型暂不可用，使用备用画架：" + e.Message);
                return false;
            }
        }
    }
}
